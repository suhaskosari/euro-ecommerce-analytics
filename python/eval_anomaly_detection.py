"""
Evaluates revenue anomaly detectors against the incidents injected by generate_data.py.

The generator injects known events, so unlike a real dataset we have ground truth and can
report precision / recall instead of "it found the three things". Two detectors are compared:

  1. Baseline   -- same-weekday trailing median, z-score > 2.5 (the original detector)
  2. STL + Poisson -- robust STL decomposition (weekly period) of daily *order counts* gives an
                   expected count (trend + weekly seasonality). Order arrivals are Poisson, so the
                   Pearson residual (observed - expected) / sqrt(expected) is approximately N(0,1)
                   and an abs(z) threshold has a real statistical meaning. The trend absorbs the Nov/Dec
                   peak that the baseline mistakes for anomalies. Revenue itself is a poor target:
                   heavy-tailed order values add noise unrelated to incidents.

The operating threshold (abs(z) > 3.5) is chosen for recall, as alerting favours catching incidents; a
full threshold sweep is published so the precision/recall trade-off is visible, not hidden.

Ground truth (revenue): checkout outage 2024-06-10..12, flash sale 2025-03-03..04.
(The January 2025 paid-search overspend is a marketing-spend anomaly, evaluated separately.)

Note: STL is fitted on the whole series (retrospective detection). A production alerting job
would need a causal detector; that trade-off is documented in the output.

Run (after stats_anomaly_detection.py):
    python python/eval_anomaly_detection.py
"""
from pathlib import Path

import numpy as np
import pandas as pd
from statsmodels.tsa.seasonal import STL

BASE = Path(__file__).resolve().parent.parent
OUT = BASE / "outputs"

TRUTH_WINDOWS = {
    "Checkout outage": ("2024-06-10", "2024-06-12"),
    "Flash-sale spike": ("2025-03-03", "2025-03-04"),
}
TRUTH_DAYS = {d.strftime("%Y-%m-%d")
              for a, b in TRUTH_WINDOWS.values() for d in pd.date_range(a, b)}


OPERATING_THRESHOLD = 3.5
SWEEP = (3.0, 3.5, 4.0, 4.5, 5.0)


def poisson_residual_z(daily: pd.DataFrame) -> pd.Series:
    y = daily["orders_count"].astype(float)
    fit = STL(y.values, period=7, robust=True, seasonal=7).fit()
    expected = np.clip(fit.trend + fit.seasonal, 1, None)
    return pd.Series((y.values - expected) / np.sqrt(expected), index=daily.index)


def score(flagged_days: set) -> dict:
    tp = len(flagged_days & TRUTH_DAYS)
    fp = len(flagged_days - TRUTH_DAYS)
    fn = len(TRUTH_DAYS - flagged_days)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    incidents = {name: any(d.strftime("%Y-%m-%d") in flagged_days for d in pd.date_range(a, b))
                 for name, (a, b) in TRUTH_WINDOWS.items()}
    return {"flagged": len(flagged_days), "tp": tp, "fp": fp, "fn": fn,
            "precision": precision, "recall": recall, "f1": f1, "incidents": incidents}


def main():
    daily = pd.read_csv(OUT / "daily_revenue_with_flags.csv", parse_dates=["date"])
    day_str = daily["date"].dt.strftime("%Y-%m-%d")

    baseline = set(day_str[daily["is_anomaly"].astype(bool)])
    z = poisson_residual_z(daily)
    stl = set(day_str[z.abs() > OPERATING_THRESHOLD])

    daily["poisson_z"] = z.round(3)
    daily["stl_poisson_anomaly"] = day_str.isin(stl)
    daily.to_csv(OUT / "daily_revenue_with_flags.csv", index=False)

    results = {"Baseline (weekday median on revenue, z > 2.5)": score(baseline),
               f"STL + Poisson residual on orders (abs(z) > {OPERATING_THRESHOLD})": score(stl)}

    lines = ["# Anomaly Detection Evaluation", "",
             "_Auto-generated by `python/eval_anomaly_detection.py`. The synthetic generator injects known "
             "incidents, which gives true ground truth to score detectors against._", "",
             f"Ground-truth anomalous days: **{len(TRUTH_DAYS)}** "
             f"({', '.join(f'{k} {a}..{b}' for k, (a, b) in TRUTH_WINDOWS.items())}) "
             f"out of **{len(daily)}** days.", "",
             "| Detector | Days flagged | True pos. | False pos. | Missed | Precision | Recall | F1 | Incidents caught |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for name, r in results.items():
        caught = ", ".join(f"{k}: {'yes' if v else 'no'}" for k, v in r["incidents"].items())
        lines.append(f"| {name} | {r['flagged']} | {r['tp']} | {r['fp']} | {r['fn']} | "
                     f"{r['precision']:.1%} | {r['recall']:.1%} | {r['f1']:.2f} | {caught} |")
    lines += ["", "## Threshold sweep (STL + Poisson residual)", "",
              "| abs(z) threshold | Days flagged | True pos. | Precision | Recall |", "|---:|---:|---:|---:|---:|"]
    for t in SWEEP:
        r = score(set(day_str[z.abs() > t]))
        lines.append(f"| {t} | {r['flagged']} | {r['tp']} | {r['precision']:.1%} | {r['recall']:.1%} |")
    lines += ["", "## Reading the result", "",
              "- Recall is measured per day, so partially detected multi-day incidents are visible as misses; "
              "'Incidents caught' is the looser per-incident view.",
              "- Precision is limited by *unlabelled* real structure in the synthetic data (Nov/Dec seasonality, "
              "Poisson noise), so some 'false positives' are statistically genuine outliers that were never injected. "
              "Treat precision as a lower bound on practical usefulness, not as a pure error rate.",
              "- STL is fitted on the full series (retrospective). A live alerting job needs a causal detector "
              "(e.g. an online seasonal baseline), which would score lower than this offline figure.",
              "- With only 5 ground-truth days these metrics have wide uncertainty; they show the detectors' "
              "relative behaviour, not a production accuracy estimate."]
    md = "\n".join(lines)
    (OUT / "anomaly_eval.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
